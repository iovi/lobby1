package iovi.lobby1.flow;

/** Версия правил игры — выбирается в настройках. */
public enum Rules {
    /** ФСМ: протоколы, доп. время, дон в первую ночь не проверяет свой отстрел, после трёх фолов — 30 с речи. */
    FSM,
    /**
     * МСЛ: без протоколов и доп. времени, лучший ход только у убитого в первую ночь, дон проверяет кого угодно,
     * после трёх фолов — речь без слова.
     */
    MSL;

    /** Выбывшие оставляют протокол (кому он положен). */
    public boolean protocols() {
        return this == FSM;
    }

    /**
     * Единственный заголосованный в нулевом круге делает лучший ход. По МСЛ — нет:
     * лучший ход только у убитого в первую ночь.
     */
    public boolean bestMoveForFirstVotedOut() {
        return this == FSM;
    }

    /** Кнопка «Доп. время» за два фола. */
    public boolean extraTime() {
        return this == FSM;
    }

    /** Дон может проверить того, в кого стрелял, и в первую ночь. */
    public boolean donChecksOwnShotFirstNight() {
        return this == MSL;
    }

    /** В ближайшей дневной речи игрок с тремя фолами не говорит, а только выставляет кандидатуру. */
    public boolean silentAfterThreeFouls() {
        return this == MSL;
    }
}