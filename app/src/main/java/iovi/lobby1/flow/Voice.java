package iovi.lobby1.flow;

/** Голос ведущего и звуковые сигналы. */
public interface Voice {
    /** Добавляет фразу в очередь объявлений. */
    void say(String text);

    /** Добавляет фразу в очередь; onDone вызывается, когда она прозвучит (или голос недоступен). */
    void say(String text, Runnable onDone);

    /** Добавляет в очередь объявлений паузу — тишину между фразами. */
    void pause(long ms);

    /** Короткий сигнал — например, «осталось 10 секунд». */
    void beep();

    /** Длинный сигнал окончания отведённого времени. */
    void endSignal();
}